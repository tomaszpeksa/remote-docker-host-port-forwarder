// WatchdogAttempt separates the application proxy from its retained real SSH
// child. A dispatch hold has no real child or Engine ID; it is not SSH evidence.
type WatchdogAttempt struct {
	Operation, Name, ContainerID                 string
	ProxyPID, ChildPID                           int
	RealChildStarted, DispatchSuppressed         bool
	StartedAt, CanceledAt, JoinedAt, CompletedAt time.Time
}
type watchdogGate struct {
	entered, release       chan struct{}
	enterOnce, releaseOnce sync.Once
}

func (g *watchdogGate) wait(ctx context.Context) error {
	g.enterOnce.Do(func() { close(g.entered) })
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-g.release:
		return ctx.Err()
	}
}
func (g *watchdogGate) open() { g.releaseOnce.Do(func() { close(g.release) }) }

// WatchdogFixture controls only selected commands on New's verified owned alias.
// It owns every selected real SSH child even when the application proxy dies.
type WatchdogFixture struct {
	*Fixture
	listener   net.Listener
	socket     string
	ctx        context.Context
	cancel     context.CancelFunc
	acceptDone chan struct{}
	workers    sync.WaitGroup
	mu         sync.Mutex
	gates      map[string]*watchdogGate
	dispatch   *watchdogGate
	attempts   []*WatchdogAttempt
	closeOnce  sync.Once
}
type watchdogRequest struct {
	Args      []string
	Operation string
	PID       int
}
type watchdogFrame struct {
	Stream string
	Data   []byte
	Exit   *int
}

func NewWatchdog(t *testing.T) *WatchdogFixture {
	t.Helper()
	f := New(t)
	f.Configure("yes", f.PublicKey, "", f.Key, "no")
	w := newWatchdogController(t, f)
	executable, err := os.Executable()
	require.NoError(t, err)
	bin := filepath.Join(f.Dir, "watchdog-bin")
	require.NoError(t, os.Mkdir(bin, 0700))
	// Only a child of the selected test gets this private launcher and marker.
	require.NoError(t, os.WriteFile(filepath.Join(bin, "ssh"), []byte("#!/bin/sh\nexec \"$RDHPF_WATCHDOG_TEST_EXECUTABLE\" -test.run '^TestWatchdogSSHProxy$' -- \"$@\"\n"), 0700))
	t.Setenv("RDHPF_WATCHDOG_TEST_EXECUTABLE", executable)
	t.Setenv("RDHPF_WATCHDOG_SOCKET", w.socket)
	t.Setenv("RDHPF_WATCHDOG_ALIAS", f.Alias)
	t.Setenv("RDHPF_WATCHDOG_SSH", f.SSH)
	t.Setenv("PATH", bin+string(os.PathListSeparator)+f.Path)
	t.Cleanup(w.Close)
	return w
}
func newWatchdogController(t *testing.T, f *Fixture) *WatchdogFixture {
	t.Helper()
	dir, err := os.MkdirTemp("/tmp", "s10-proxy-")
	require.NoError(t, err)
	listener, err := net.Listen("unix", filepath.Join(dir, "controller"))
	require.NoError(t, err)
	ctx, cancel := context.WithCancel(context.Background())
	w := &WatchdogFixture{Fixture: f, listener: listener, socket: filepath.Join(dir, "controller"), ctx: ctx, cancel: cancel, acceptDone: make(chan struct{}), gates: make(map[string]*watchdogGate)}
	go func() {
		defer close(w.acceptDone)
		for {
			conn, err := listener.Accept()
			if err != nil {
				return
			}
			w.workers.Add(1)
			go func() { defer w.workers.Done(); w.serve(conn) }()
		}
	}()
	t.Cleanup(func() { w.Close(); require.NoError(t, os.RemoveAll(dir)) })
	return w
}

func (w *WatchdogFixture) Gate(operation string) (<-chan struct{}, func()) {
	w.T.Helper()
	require.Contains(w.T, []string{"events", "ping", "inspect"}, operation, "unknown watchdog operation")
	w.mu.Lock()
	defer w.mu.Unlock()
	require.Nil(w.T, w.gates[operation], "a gate is armed only once")
	g := &watchdogGate{entered: make(chan struct{}), release: make(chan struct{})}
	w.gates[operation] = g
	return g.entered, g.open
}

// GatePingDispatch is used only to isolate the real inspection cancellation
// case from health generated by probes. Cancellation never releases a late run.
func (w *WatchdogFixture) GatePingDispatch() (<-chan struct{}, func()) {
	w.T.Helper()
	w.mu.Lock()
	defer w.mu.Unlock()
	require.Nil(w.T, w.dispatch)
	w.dispatch = &watchdogGate{entered: make(chan struct{}), release: make(chan struct{})}
	return w.dispatch.entered, w.dispatch.open
}
func (w *WatchdogFixture) Snapshot() []WatchdogAttempt {
	w.mu.Lock()
	defer w.mu.Unlock()
	out := make([]WatchdogAttempt, len(w.attempts))
	for i, a := range w.attempts {
		out[i] = *a
	}
	return out
}
func (w *WatchdogFixture) Close() {
	w.closeOnce.Do(func() {
		w.cancel()
		_ = w.listener.Close()
		<-w.acceptDone
		w.mu.Lock()
		for _, g := range w.gates {
			g.open()
		}
		if w.dispatch != nil {
			w.dispatch.open()
		}
		w.mu.Unlock()
		w.workers.Wait()
		for _, a := range w.Snapshot() {
			w.T.Logf("WATCHDOG_ATTEMPT %+v", a)
			if a.RealChildStarted {
				require.False(w.T, a.JoinedAt.IsZero(), "real SSH child lacks Wait receipt")
			}
			require.False(w.T, a.CompletedAt.IsZero(), "controller not joined")
		}
		w.T.Log("WATCHDOG_FIXTURE_JOINED all controller connections and retained real SSH children")
	})
}

var watchdogPingCommand = regexp.MustCompile(`^docker run --rm --name (rdhpf-ping-[0-9]+) --label rdhpf.health-check=true alpine:latest echo works$`)
var watchdogContainerID = regexp.MustCompile(`[a-f0-9]{64}`)
var watchdogAlias = regexp.MustCompile(`^rdhpf-trust-[a-f0-9]{16}$`)
var watchdogForward = regexp.MustCompile(`^127\.0\.0\.1:[0-9]+:localhost:[0-9]+$`)

const watchdogEvents = `sh -c "docker events --format '{{json .}}' --filter type=container --filter event=start --filter event=die --filter event=stop"`

// Only the existing application's concrete SSH options may reach the retained
// provider. This is a test boundary, not a general-purpose SSH parser.
func watchdogOptions(args []string) bool {
	batch := false
	for i := 0; i < len(args); i++ {
		switch args[i] {
		case "-MN":
		case "-o", "-S", "-O", "-L", "-p":
			if i+1 == len(args) {
				return false
			}
			option, value := args[i], args[i+1]
			i++
			switch option {
			case "-o":
				switch value {
				case "BatchMode=yes":
					batch = true
				case "ControlMaster=yes", "ForkAfterAuthentication=no", "ControlPersist=no", "ServerAliveInterval=15", "ServerAliveCountMax=2", "TCPKeepAlive=yes", "ExitOnForwardFailure=yes":
				default:
					if !strings.HasPrefix(value, "ControlPath=") || !filepath.IsAbs(strings.TrimPrefix(value, "ControlPath=")) {
						return false
					}
				}
			case "-S":
				if !filepath.IsAbs(value) {
					return false
				}
			case "-O":
				if value != "check" && value != "forward" && value != "cancel" && value != "exit" {
					return false
				}
			case "-L":
				if !watchdogForward.MatchString(value) {
					return false
				}
			case "-p":
				if value != "2222" {
					return false
				}
			}
		default:
			return false
		}
	}
	return batch
}

func watchdogShellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

func watchdogOperation(args []string, alias string) (operation, name, id string, err error) {
	destination := -1
	for i, arg := range args {
		if arg == "--" {
			destination = i + 1
			break
		}
	}
	if destination < 0 || destination >= len(args) || args[destination] != alias || !watchdogAlias.MatchString(alias) || !watchdogOptions(args[:destination-1]) {
		return "", "", "", fmt.Errorf("watchdog fixture refuses destination")
	}
	if destination == len(args)-1 {
		return "other", "", "", nil
	} // retained Master's native argv
	if destination+2 != len(args) {
		return "", "", "", fmt.Errorf("watchdog fixture refuses extra operands")
	}
	command := args[destination+1]
	if match := watchdogPingCommand.FindStringSubmatch(command); match != nil {
		return "ping", match[1], "", nil
	}
	if command == watchdogEvents {
		return "events", "", "", nil
	}
	if id := watchdogContainerID.FindString(command); id != "" {
		for _, format := range []string{"{{json .HostConfig.PortBindings}}", "{{json .Config.Labels}}", `{{index .Config.Labels "rdhpf.test-infrastructure"}}`} {
			expected := "sh -c " + watchdogShellQuote("docker inspect --format '"+format+"' -- "+watchdogShellQuote(id))
			if command == expected {
				if format == "{{json .HostConfig.PortBindings}}" {
					return "inspect", "", id, nil
				}
				return "other", "", "", nil
			}
		}
	}
	for _, raw := range []string{"docker version --format '{{.Server.Version}}'", "docker ps --no-trunc --format '{{.ID}}'"} {
		if command == "sh -c "+strconv.Quote(raw) {
			return "other", "", "", nil
		}
	}
	return "", "", "", fmt.Errorf("watchdog fixture refuses command")
}

func (w *WatchdogFixture) serve(conn net.Conn) {
	defer conn.Close()
	// A local half-open client must not hold fixture cleanup indefinitely.
	_ = conn.SetReadDeadline(time.Now().Add(5 * time.Second))
	var request watchdogRequest
	if json.NewDecoder(conn).Decode(&request) != nil {
		return
	}
	_ = conn.SetReadDeadline(time.Time{})
	operation, name, id, err := watchdogOperation(request.Args, w.Alias)
	if err != nil || operation != request.Operation || operation == "other" {
		code := 97
		_ = json.NewEncoder(conn).Encode(watchdogFrame{Exit: &code})
		return
	}
	ctx, cancel := context.WithCancel(w.ctx)
	defer cancel()
	a := &WatchdogAttempt{Operation: operation, Name: name, ContainerID: id, ProxyPID: request.PID, StartedAt: time.Now()}
	w.mu.Lock()
	w.attempts = append(w.attempts, a)
	dispatch := w.dispatch
	w.mu.Unlock()
	disconnected := make(chan struct{})
	go func() {
		defer close(disconnected)
		_, _ = io.Copy(io.Discard, conn)
		w.mu.Lock()
		if a.JoinedAt.IsZero() {
			a.CanceledAt = time.Now()
		}
		w.mu.Unlock()
		cancel()
	}()
	defer func() { _ = conn.Close(); <-disconnected; w.mu.Lock(); a.CompletedAt = time.Now(); w.mu.Unlock() }()
	if operation == "ping" && dispatch != nil {
		w.mu.Lock()
		a.DispatchSuppressed = true
		w.mu.Unlock()
		if dispatch.wait(ctx) != nil {
			return
		}
	}
	if ctx.Err() != nil {
		return
	}
	// The retained absolute SSH provider and exact original application argv are
	// the only executable/arguments accepted by this concrete fixture.
	cmd := exec.CommandContext(ctx, w.SSH, request.Args...)
	output := &watchdogOutput{fixture: w, ctx: ctx, conn: conn, operation: operation}
	cmd.Stdout = &watchdogOutputStream{output: output, stream: "stdout"}
	cmd.Stderr = &watchdogOutputStream{output: output, stream: "stderr"}
	cmd.WaitDelay = 2 * time.Second
	err = cmd.Start()
	if err == nil {
		w.mu.Lock()
		a.RealChildStarted = true
		a.ChildPID = cmd.Process.Pid
		w.mu.Unlock()
		err = cmd.Wait()
		w.mu.Lock()
		a.JoinedAt = time.Now()
		w.mu.Unlock()
	}
	// Keep controlled completion pending separately from the real-child Wait.
	w.mu.Lock()
	gate := w.gates[operation]
	w.mu.Unlock()
	if gate != nil {
		<-gate.release
	}
	code := 0
	if err != nil {
		code = 1
	}
	output.mu.Lock()
	_ = json.NewEncoder(conn).Encode(watchdogFrame{Exit: &code})
	output.mu.Unlock()
}

type watchdogOutput struct {
	fixture   *WatchdogFixture
	ctx       context.Context
	conn      net.Conn
	operation string
	mu        sync.Mutex
}
type watchdogOutputStream struct {
	output *watchdogOutput
	stream string
}

func (s *watchdogOutputStream) Write(data []byte) (int, error) {
	o := s.output
	if s.stream == "stdout" {
		o.fixture.mu.Lock()
		gate := o.fixture.gates[o.operation]
		o.fixture.mu.Unlock()
		if gate != nil {
			if err := gate.wait(o.ctx); err != nil {
				return 0, err
			}
		}
	}
	o.mu.Lock()
	defer o.mu.Unlock()
	if err := json.NewEncoder(o.conn).Encode(watchdogFrame{Stream: s.stream, Data: data}); err != nil {
		return 0, err
	}
	return len(data), nil
}

// The marker binds the proxy to this test executable and a private controller;
// passthrough is only the disposable runner's native OpenSSH, never an arbitrary
// executable named by an environment variable. Same-UID hostile replacement is
// outside the fixture's trusted actor contract.
func watchdogProxyEnvironment(socket, alias, ssh string) bool {
	if !watchdogAlias.MatchString(alias) || !filepath.IsAbs(socket) || !filepath.IsAbs(ssh) || filepath.Base(socket) != "controller" || !strings.HasPrefix(filepath.Base(filepath.Dir(socket)), "s10-proxy-") {
		return false
	}
	dir, err := os.Lstat(filepath.Dir(socket))
	if err != nil || !dir.IsDir() || dir.Mode().Perm() != 0700 {
		return false
	}
	sock, err := os.Lstat(socket)
	if err != nil || sock.Mode()&os.ModeSocket == 0 {
		return false
	}
	provider, err := os.Stat(ssh)
	if err != nil || !provider.Mode().IsRegular() || provider.Mode().Perm()&0111 == 0 {
		return false
	}
	native, err := os.Stat("/usr/bin/ssh")
	if err != nil || !os.SameFile(provider, native) {
		return false
	}
	executable, err := os.Executable()
	if err != nil {
		return false
	}
	self, err := os.Stat(executable)
	if err != nil {
		return false
	}
	marker, err := os.Stat(os.Getenv("RDHPF_WATCHDOG_TEST_EXECUTABLE"))
	return err == nil && os.SameFile(self, marker)
}

// WatchdogProxyMain has no remote child for cancellation to orphan. Closing its
// controller connection cancels the real child owned and joined by the fixture.
func WatchdogProxyMain() int {
	socket, alias, ssh := os.Getenv("RDHPF_WATCHDOG_SOCKET"), os.Getenv("RDHPF_WATCHDOG_ALIAS"), os.Getenv("RDHPF_WATCHDOG_SSH")
	if !watchdogProxyEnvironment(socket, alias, ssh) {
		return 97
	}
	args := os.Args
	for len(args) > 0 && args[0] != "--" {
		args = args[1:]
	}
	if len(args) == 0 {
		return 97
	}
	args = args[1:]
	operation, _, _, err := watchdogOperation(args, alias)
	if err != nil {
		return 97
	}
	if operation == "other" {
		if syscall.Exec(ssh, append([]string{ssh}, args...), os.Environ()) != nil {
			return 97
		}
		return 97
	}
	conn, err := net.DialUnix("unix", nil, &net.UnixAddr{Name: socket, Net: "unix"})
	if err != nil {
		return 97
	}
	defer conn.Close()
	if json.NewEncoder(conn).Encode(watchdogRequest{Args: args, Operation: operation, PID: os.Getpid()}) != nil {
		return 97
	}
	decoder := json.NewDecoder(conn)
	for {
		var frame watchdogFrame
		if decoder.Decode(&frame) != nil {
			return 97
		}
		if frame.Exit != nil {
			return *frame.Exit
		}
		var writer io.Writer = os.Stdout
		if frame.Stream == "stderr" {
			writer = os.Stderr
		}
		if _, err := writer.Write(frame.Data); err != nil {
			return 97
		}
	}
}

// FailAfterCompletedPing is selected only by the hosted diagnostic invocation.
// The real probe must already have an Engine destroy receipt and no leftover,
// so the pre-fix failure can expose missing accounting without orphaning work.
func (w *WatchdogFixture) FailAfterCompletedPing() {
	if os.Getenv("RDHPF_WATCHDOG_FAILURE_CONTROL") != "1" {
		return
	}
	w.T.Helper()
	var attempt WatchdogAttempt
	require.Eventually(w.T, func() bool {
		for _, a := range w.Snapshot() {
			if a.Operation == "ping" && a.RealChildStarted && !a.DispatchSuppressed && !a.JoinedAt.IsZero() && !a.CompletedAt.IsZero() {
				attempt = a
				return true
			}
		}
		return false
	}, 45*time.Second, 10*time.Millisecond, "failure control requires completed actual SSH probe")
	raw := w.Docker("events", "--since", attempt.StartedAt.Add(-time.Second).Format(time.RFC3339Nano), "--until", time.Now().Format(time.RFC3339Nano), "--filter", "container="+attempt.Name, "--format", `{{.Action}} {{.Actor.ID}} {{index .Actor.Attributes "name"}} {{index .Actor.Attributes "rdhpf.health-check"}}`)
	id := ""
	for _, line := range strings.Split(raw, "\n") {
		fields := strings.Fields(line)
		if len(fields) == 4 && fields[0] == "destroy" && fields[2] == attempt.Name && fields[3] == "true" {
			require.Regexp(w.T, `^[a-f0-9]{64}$`, fields[1])
			id = fields[1]
		}
	}
	require.NotEmpty(w.T, id, "real Engine destroy receipt required before diagnostic failure")
	require.Empty(w.T, w.Docker("ps", "-aq", "--no-trunc", "--filter", "name=^/"+attempt.Name+"$"), "failure control refuses uncertain remote disposition")
	w.T.Logf("WATCHDOG_FAILURE_CONTROL_DISPATCH name=%s Engine_ID=%s removed_before_failure=true", attempt.Name, id)
	w.T.Fatal("WATCHDOG_INTENTIONAL_FAILURE_AFTER_DISPATCH")
}

// SchedulePingAccounting is called by the already-registered local-owner cleanup
// after joining Run/CLI and Master, before backend/config retirement. Register
// every attempt before making any assertion: failure observing one must not
// discard the remaining attempts. Failed local joining records uncertainty only:
// never infer remote retirement or remove resources from a missing Wait receipt.
func (w *WatchdogFixture) SchedulePingAccounting(requireCreated, localJoined bool) int {
	var attempts []WatchdogAttempt
	for _, a := range w.Snapshot() {
		if a.Operation == "ping" {
			attempts = append(attempts, a)
		}
	}
	completed := 0
	w.T.Cleanup(func() {
		w.T.Logf("WATCHDOG_PING_ACCOUNT_COMPLETE attempts=%d unknown=%d", len(attempts), len(attempts)-completed)
	})
	for i := len(attempts) - 1; i >= 0; i-- {
		a := attempts[i]
		w.T.Cleanup(func() {
			observed := false
			defer func() {
				if !observed {
					w.T.Logf("WATCHDOG_PING_ACCOUNT_UNKNOWN name=%s disposition=uncertain; unverified identities are preserved", a.Name)
				}
			}()
			if !localJoined {
				w.T.Errorf("WATCHDOG_PING_LOCAL_JOIN_UNCERTAIN name=%s; remote observation deferred", a.Name)
				return
			}
			w.accountPing(a, requireCreated)
			observed = true
			completed++
		})
	}
	return len(attempts)
}

// Exact attempt-name/Engine-ID accounting, never a label sweep or an assumption
// that canceling local SSH removed an interrupted remote container.
func (w *WatchdogFixture) accountPing(a WatchdogAttempt, requireCreated bool) {
	w.T.Helper()
	raw := w.Docker("events", "--since", a.StartedAt.Add(-time.Second).Format(time.RFC3339Nano), "--until", time.Now().Format(time.RFC3339Nano), "--filter", "container="+a.Name, "--format", "{{json .}}")
	ids := map[string]bool{}
	for _, line := range strings.Split(raw, "\n") {
		if line == "" {
			continue
		}
		var event struct {
			Actor struct {
				ID         string
				Attributes map[string]string
			}
		}
		require.NoError(w.T, json.Unmarshal([]byte(line), &event))
		if event.Actor.Attributes["name"] == a.Name {
			require.Equal(w.T, "true", event.Actor.Attributes["rdhpf.health-check"])
			require.Regexp(w.T, `^[a-f0-9]{64}$`, event.Actor.ID)
			ids[event.Actor.ID] = true
		}
	}
	if requireCreated && !a.DispatchSuppressed {
		require.Len(w.T, ids, 1, "exact ping must have an Engine ID")
	} else {
		require.LessOrEqual(w.T, len(ids), 1)
	}
	left := w.Docker("ps", "-aq", "--no-trunc", "--filter", "name=^/"+a.Name+"$")
	if left != "" {
		require.True(w.T, ids[left], "unaccounted leftover is not cleanup authority")
		require.Equal(w.T, "true", w.Docker("inspect", "--format", `{{index .Config.Labels "rdhpf.health-check"}}`, left))
		w.Docker("rm", "-f", left)
	}
	w.T.Logf("WATCHDOG_PING_ACCOUNT name=%s Engine_IDs=%v no_ID_observed=%v leftover_before_cleanup=%q suppressed=%v", a.Name, ids, len(ids) == 0, left, a.DispatchSuppressed)
	require.Empty(w.T, w.Docker("ps", "-aq", "--no-trunc", "--filter", "name=^/"+a.Name+"$"))
}
